from __future__ import annotations

from pathlib import Path
import re
import sys
from docx import Document

ROOT = Path(__file__).resolve().parents[1]
DOC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "MMOSON_v7.docx"
D = Document(DOC)
paras = [" ".join(p.text.split()) for p in D.paragraphs]
cells = []
for ti, table in enumerate(D.tables):
    for ri, row in enumerate(table.rows):
        for ci, cell in enumerate(row.cells):
            cells.append((ti, ri, ci, " ".join(cell.text.split())))

TEXT = "\n".join(paras)
ALL = TEXT + "\n" + "\n".join(x[3] for x in cells)
errors = []
notes = []


def require(needle: str, label: str) -> None:
    if needle not in ALL:
        errors.append(f"не найдено: {label}: {needle}")


def forbid(needle: str, label: str) -> None:
    if needle in ALL:
        errors.append(f"остаточное противоречие: {label}: {needle}")


def table_require(ti: int, needle: str, label: str) -> None:
    table_text = "\n".join(c[3] for c in cells if c[0] == ti)
    if needle not in table_text:
        errors.append(f"таблица {ti + 1}: {label}: {needle}")

