OK, BAD, NOTE = [], [], []
def chk(name, calc, doc, tol=0.02, unit=''):
    if doc == 0:
        rel = abs(calc)
    else:
        rel = abs(calc-doc)/abs(doc)
    s = f'{name}: расчёт {calc:.4g}{unit}, в документе {doc:.4g}{unit}, расх. {rel*100:.2f} %'
    (OK if rel <= tol else BAD).append(s)

